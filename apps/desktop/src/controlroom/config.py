def parse_ladder(text: str) -> tuple[list[LadderRow], list[str]]:
    """Parse a LADDER table into rows plus per-row error strings.

    Blank lines and #-comments are skipped, mirroring run.sh's reader. Bad
    rows produce errors and are dropped; parsing never raises.
    """
    rows: list[LadderRow] = []
    errors: list[str] = []
    for lineno, line in enumerate(text.splitlines(), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        tokens = stripped.split()
        if len(tokens) != 7:
            errors.append(f"line {lineno}: expected 7 columns "
                          f"(label height width video_bitrate maxrate bufsize "
                          f"audio_bitrate), got {len(tokens)}")
            continue
        label, h, w, vb, mx, bf, ab = tokens
        if not (_is_int(h) and _is_int(w)):
            errors.append(f"line {lineno}: height and width must be integers "
                          f"(got '{h}' '{w}')")
            continue
        bad = [v for v in (vb, mx, bf, ab) if not BITRATE_RE.fullmatch(v)]
        if bad:
            errors.append(f"line {lineno}: not a bitrate: {', '.join(repr(b) for b in bad)}")
            continue
        rows.append(LadderRow(label, int(h), int(w), vb, mx, bf, ab))
    return rows, errors


def format_ladder(rows: list[LadderRow]) -> str:
    """Render rows column-aligned like run.sh's default table."""
    cols = list(zip(*[(r.label, str(r.height), str(r.width), r.video_bitrate,
                       r.maxrate, r.bufsize, r.audio_bitrate) for r in rows]))
    # Minimum widths reproduce the engine's hand-tuned alignment exactly.
    widths = [max(minw, max(len(v) for v in col))
              for col, minw in zip(cols, (5, 4, 4, 6, 6, 6, 5))]
    lines = []
    for r in rows:
        vals = (r.label, str(r.height), str(r.width), r.video_bitrate,
                r.maxrate, r.bufsize, r.audio_bitrate)
        lines.append(vals[0].ljust(widths[0])
                     + "".join(" " + v.rjust(w) for v, w in zip(vals[1:], widths[1:])))
    return "\n".join(lines) + "\n"


def validate(specs: dict[str, FieldSpec], values: dict[str, str]) -> list[str]:
    """Check values against specs, mirroring the engines' startup rejections.

    Returns error strings (warnings are prefixed 'warning:'); never raises.
    Absent keys fall back to the spec default, as the engines would resolve
    them.
    """

    def eff(name: str) -> str | None:
        spec = specs.get(name)
        return None if spec is None else values.get(name, spec.default)

    errors: list[str] = []
    for name, spec in specs.items():
        if name not in values:
            continue
        v = values[name]
        if spec.kind == "enum" and spec.choices and v not in spec.choices:
            errors.append(f"{name} must be one of {'|'.join(spec.choices)} (got '{v}')")
        elif spec.kind == "int" and not _is_int(v):
            errors.append(f"{name} must be an integer (got '{v}')")
        elif spec.kind == "bool" and v not in _BOOL_VALUES:
            errors.append(f"{name} must be exactly 'true' or 'false' (got '{v}')")
        elif spec.kind == "bitrate" and not BITRATE_RE.fullmatch(v):
            errors.append(f"{name} must be a bitrate like 400k or 2m (got '{v}')")

    # run.sh: MPEG-TS cannot carry HEVC/AV1 or Opus.
    if eff("HLS_SEGMENT_TYPE") == "mpegts" and not (
        eff("VIDEO_CODEC") == "h264" and eff("AUDIO_CODEC") == "aac"
    ):
        errors.append("HLS_SEGMENT_TYPE=mpegts only supports h264+aac")

    # run.sh: the ladder window must keep at least one tier.
    ladder = specs.get("LADDER")
    min_h, max_h = eff("MIN_RESOLUTION_HEIGHT"), eff("MAX_RESOLUTION_HEIGHT")
    if ladder is not None and _is_int(min_h) and _is_int(max_h):
        lo, hi = int(min_h), int(max_h)
        rows, row_errors = parse_ladder(values.get("LADDER", ladder.default))
        errors.extend(f"LADDER {e}" for e in row_errors)
        if lo >= hi:
            errors.append(f"MIN_RESOLUTION_HEIGHT={lo} must be below "
                          f"MAX_RESOLUTION_HEIGHT={hi}")
        elif not any(lo <= r.height <= hi for r in rows):
            errors.append(f"no ladder tiers between MIN_RESOLUTION_HEIGHT={lo} "
                          f"and MAX_RESOLUTION_HEIGHT={hi}.")

    # encode-batch.sh clamps rather than rejecting; surface it as a warning.
    jobs = eff("PARALLEL_JOBS")
    if jobs is not None and _is_int(jobs) and int(jobs) > 8:
        errors.append(f"warning: PARALLEL_JOBS={jobs} is above the max "
                      f"recommended value 8; encode-batch.sh clamps it to 8")
    return errors


def resolve_roots(engine_root: Path, values: dict[str, str]) -> dict[str, Path]:
    """Resolve run.sh's directory settings the way the script does.

    Absolute paths pass through; relative paths anchor to the engine root
    (run.sh resolves them against SCRIPT_DIR, not the caller's cwd). The
    symbolic $SCRIPT_DIR / $WORK_ROOT anchors used by the spec defaults are
    expanded here. ENCODED_ROOT/STATE_ROOT/LOG_ROOT derive from WORK_ROOT
    when not overridden.
    """
    engine_root = Path(engine_root)

    def resolve(value: str, work: Path | None = None) -> Path:
        if value.startswith("$SCRIPT_DIR/"):
            path = engine_root / value[len("$SCRIPT_DIR/"):]
        elif work is not None and value.startswith("$WORK_ROOT/"):
            path = work / value[len("$WORK_ROOT/"):]
        else:
            p = Path(value)
            path = p if p.is_absolute() else engine_root / p
        return Path(os.path.normpath(path))

    def eff(name: str, fallback: str) -> str:
        return values.get(name) or fallback

    work = resolve(eff("WORK_ROOT", "$SCRIPT_DIR/video-work"))
    return {
        "input": resolve(eff("INPUT_ROOT", "$SCRIPT_DIR/video")),
        "hls": resolve(eff("HLS_ROOT", "$SCRIPT_DIR/hls")),
        "work": work,
        "processed": resolve(eff("PROCESSED_ROOT", "$SCRIPT_DIR/video-done")),
        "encoded": resolve(eff("ENCODED_ROOT", "$WORK_ROOT/encoded"), work),
        "state": resolve(eff("STATE_ROOT", "$WORK_ROOT/state"), work),
        "logs": resolve(eff("LOG_ROOT", "$WORK_ROOT/logs"), work),
    }


def _app_settings_path() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME")
    root = Path(base) if base else Path.home() / ".config"
    return root / "videohls-controlroom" / "app.json"


def load_app_settings() -> dict:
    """Load the GUI's own settings; missing or corrupt file yields {}."""
    try:
        data = json.loads(_app_settings_path().read_text())
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def save_app_settings(settings: dict) -> None:
    """Persist GUI settings (engine_path, ffmpeg_dir, window_size, ...) atomically."""
    path = _app_settings_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(settings, indent=2, sort_keys=True) + "\n")
    os.replace(tmp, path)


def _is_int(v) -> bool:
    try:
        int(v)
    except (TypeError, ValueError):
        return False
    return True
