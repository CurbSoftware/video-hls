"""Typed configuration surface for both engines (run.sh, encode-batch.sh).

The FieldSpec tables mirror the engines' own ``${VAR:-default}`` blocks; the
engines are the source of truth and this module must never invent a default.
Values are kept as strings exactly as bash sees them - booleans are the
literal "true"/"false", ints are digit strings, paths may contain the
symbolic ``$SCRIPT_DIR``/``$RUN_DIR``/``$WORK_ROOT`` anchors.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from pathlib import Path

# Bitrate values as the engines accept them: bare bits or a k/m suffix
# (run.sh bitrate_to_bps understands [kK] and [mM]).
BITRATE_RE = re.compile(r"\d+[kKmM]?")

_BOOL_VALUES = ("true", "false")

_LOGLEVELS = ("quiet", "error", "warning", "info", "verbose", "debug")
_HWACCEL = ("auto", "nvenc", "qsv", "vaapi", "videotoolbox", "none")


@dataclass(frozen=True)
class FieldSpec:
    """One engine setting: name, bash-level default, and UI metadata."""

    name: str
    default: str
    kind: str  # "str"|"int"|"bool"|"enum"|"path"|"bitrate"|"ladder"
    choices: tuple[str, ...] = ()
    help: str = ""
    label: str = ""
    group: str = ""


@dataclass
class LadderRow:
    """One rendition tier; a row drives both the encode and the playlist."""

    label: str
    height: int
    width: int
    video_bitrate: str
    maxrate: str
    bufsize: str
    audio_bitrate: str


